import { test, expect } from '@playwright/test';
test('登录、配对、Agent 提案和本人确认共用一份历史',async({page,playwright},info)=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await expect(page.getByRole('heading',{name:'登录'})).toBeVisible();
 await page.getByLabel('管理员密码').fill('isolated-browser-test-password');await page.getByRole('button',{name:'登录',exact:true}).click();
 await page.getByRole('navigation',{name:'主要导航'}).getByRole('button',{name:'设置',exact:true}).click();
 const panel=page.getByRole('region',{name:'设备与 Agent'});
 await expect(panel.getByRole('heading',{name:'手机配对'})).toBeVisible();
 const mobile=await playwright.request.newContext({baseURL:'http://127.0.0.1:19766'});
 const pair=await (await mobile.post('/api/clients/v1/pairings',{data:{name:'browser-contract-'+info.project.name}})).json();
 await panel.getByLabel('手机显示的八位配对码').fill(pair.code);await panel.getByRole('button',{name:'批准设备配对'}).click();
 await expect(panel.getByRole('status')).toContainText('配对已批准');
 const credentials=await (await mobile.post('/api/clients/v1/pairings/poll',{data:{pairing_id:pair.pairing_id,poll_secret:pair.poll_secret}})).json();
 const device=await playwright.request.newContext({baseURL:'http://127.0.0.1:19766',extraHTTPHeaders:{Authorization:'Bearer '+credentials.access_token}});
 await panel.getByLabel('调用方名称').fill('contract-agent-'+info.project.name);
 await panel.getByLabel('新增日志与记录',{exact:true}).check();await panel.getByLabel('提出修改建议',{exact:true}).check();await panel.getByLabel('读取待确认事项',{exact:true}).check();
 await panel.getByRole('button',{name:'创建 Agent 授权'}).click();
 const token=await panel.locator('.private-token').textContent();expect(token).toBeTruthy();
 const agent=await playwright.request.newContext({baseURL:'http://127.0.0.1:19766',extraHTTPHeaders:{Authorization:'Bearer '+token}});
 const text='多端测试任务-'+info.project.name;
 const result=await agent.post('/api/clients/v1/commands',{data:{request_id:crypto.randomUUID(),operation:'create_record',reason:text,data:{kind:'task',date:'2026-10-26',text}}});expect(result.ok()).toBeTruthy();
 await expect(panel.locator('.reminder-row').filter({hasText:text})).toBeVisible();
 await panel.locator('.reminder-row').filter({hasText:text}).getByRole('button',{name:'查看差异'}).click();
 await page.getByRole('dialog').getByRole('button',{name:'确认保存'}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 const snapshot=await (await device.get('/api/clients/v1/snapshot')).json();expect(snapshot.data.tasks.some((t:any)=>t.text===text)).toBe(true);
 const tasks=await (await agent.get('/api/clients/v1/resources/tasks')).json();expect(tasks.items.some((t:any)=>t.text===text)).toBe(true);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 await page.screenshot({path:info.outputPath('client-settings.png'),fullPage:true});
 await panel.getByRole('button',{name:'退出登录'}).click();await expect(page.getByRole('heading',{name:'登录'})).toBeVisible();
 expect(errors).toEqual([]);await mobile.dispose();await device.dispose();await agent.dispose();
});
