import { test, expect } from '@playwright/test';

test('创建并关联任务，快捷确认与跨页面状态一致', async ({page}, info) => {
  await page.goto('/');
  const nav = page.getByRole('navigation', {name:'主要导航'});
  const go = (name: string) => nav.getByRole('button', {name, exact:true}).click();
  const task = `快捷任务 ${info.project.name}`;
  const goal = `快捷目标 ${info.project.name}`;
  const dialog = page.getByRole('dialog');
  await go('总览');
  await page.getByRole('button', {name:'建立目标', exact:true}).click();
  await dialog.getByLabel('目标名称').fill(goal);
  await dialog.getByLabel('完成标准').fill('完成验收');
  await dialog.getByRole('button', {name:'保存／预览修改'}).click();
  await expect(dialog).toHaveCount(0);
  await page.getByRole('button', {name:'新增任务', exact:true}).click();
  const input = page.getByRole('textbox', {name:'记录内容', exact:true});
  await input.fill(task);
  await page.getByRole('combobox', {name:'关联目标', exact:true}).selectOption({label:goal});
  await page.route('**/api/tasks', route => route.fulfill({status:503, contentType:'application/json', body:JSON.stringify({detail:'测试保存失败，请重试'})}), {times:1});
  await page.getByRole('button', {name:'保存任务', exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('测试保存失败');
  await expect(input).toHaveValue(task);
  await page.getByRole('button', {name:'保存任务', exact:true}).click();
  await expect(input).toHaveValue('');
  await go('概述');
  const today = page.getByRole('region', {name:'今日任务', exact:true});
  const goalCard = page.locator('.summary-goal').filter({hasText:goal});
  await expect(goalCard).toContainText(task);
  await today.getByRole('button').filter({hasText:task}).click();
  await dialog.getByRole('button', {name:'完成任务', exact:true}).click();
  await expect(dialog.getByText(task, {exact:true})).toHaveCount(1);
  await expect(dialog).toContainText('待进行');
  await expect(dialog).toContainText('已完成');
  await dialog.getByRole('button', {name:'拒绝修改'}).click();
  await expect(today.getByRole('button').filter({hasText:task})).toContainText('待进行');
  await today.getByRole('button').filter({hasText:task}).click();
  await dialog.getByRole('button', {name:'完成任务', exact:true}).click();
  await dialog.getByRole('button', {name:'确认保存'}).click();
  await expect(dialog).toHaveCount(0);
  await expect(today.getByRole('button').filter({hasText:task})).toContainText('已完成');
  await expect(goalCard).not.toContainText(task);
  await expect(goalCard).toContainText('未计算');
  await go('总览');
  await expect(page.getByRole('region', {name:'今日任务'}).locator('.today-task').filter({hasText:task})).toContainText('已完成');
  await go('日志与任务');
  await expect(page.locator('.timeline-entry').filter({hasText:task}).filter({hasText:'状态：待进行 → 已完成'})).toHaveCount(1);
  await expect(page.locator('.timeline-entry').filter({hasText:task}).filter({hasText:'创建任务'})).toHaveCount(1);
  await go('每日回顾');
  const review = page.getByRole('region', {name:'当日回顾'});
  await review.getByText('查看记录与计划', {exact:true}).click();
  await expect(review.locator('.review-sources').getByText(`${task}：状态：待进行 → 已完成 · 修订 2`, {exact:true})).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
